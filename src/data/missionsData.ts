export function getEraForYear(year: number): EraInfo {
  for (const era of HISTORICAL_ERAS) {
    if (year >= era.startYear && year <= era.endYear) {
      return era;
    }
  }
  return HISTORICAL_ERAS[HISTORICAL_ERAS.length - 1];
}

export function getLifeStage(age: number): { stage: LifeStage; label: string; icon: string; range: string } {
  if (age <= 5) return { stage: 'infancy', label: 'Infancy & Toddler', icon: '🍼', range: '0-5' };
  if (age <= 12) return { stage: 'childhood', label: 'Childhood & Grade School', icon: '🎒', range: '6-12' };
  if (age <= 17) return { stage: 'youth', label: 'Teenage Youth & High School', icon: '🛹', range: '13-17' };
  if (age <= 29) return { stage: 'young_adult', label: 'Young Adult & Discovery', icon: '🎓', range: '18-29' };
  if (age <= 49) return { stage: 'prime_adult', label: 'Prime Career & Family', icon: '💼', range: '30-49' };
  if (age <= 69) return { stage: 'senior', label: 'Senior Master & Mentorship', icon: '🏛️', range: '50-69' };
  if (age <= 89) return { stage: 'golden_elder', label: 'Golden Elder & Wisdom', icon: '🍵', range: '70-89' };
  return { stage: 'centenarian', label: 'Centenarian Legend (100+)', icon: '👑', range: '90-100+' };
}
